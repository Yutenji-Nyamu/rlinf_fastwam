"""Dojo training with accepted Clean driver/cleanup and bounded new checkpoints."""

import importlib.util
import json
import os
import resource
import shutil
import subprocess
import sys
import time
from pathlib import Path


def main():
    d = Path(os.environ["DOJO_GRPO_DEPLOYMENT"])
    plan = json.loads((d / "plan.json").read_text())
    phase = sys.argv[sys.argv.index("--config-name") + 1]
    soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
    resource.setrlimit(resource.RLIMIT_NOFILE, (min(4096, hard), hard))
    sys.path.insert(0, plan["training_source"])
    from rlinf.runners.embodied_runner import EmbodiedRunner

    original_save = EmbodiedRunner._save_checkpoint

    def save_latest(self):
        original_save(self)  # Full actor + optimizer save must finish first.
        root = (
            Path(self.cfg.runner.logger.log_path)
            / self.cfg.runner.logger.experiment_name
            / "checkpoints"
        ).resolve()
        current = root / f"global_step_{self.global_step}"
        assert current.is_dir()
        (current / "dojo-complete.json").write_text(
            json.dumps({"step": self.global_step, "time": time.time()})
        )
        # Only checkpoints generated by this new Dojo run; no old experiment or
        # protected-eval path can enter this deletion list. Keep all small logs.
        removed = []
        for old in root.glob("global_step_*"):
            if old == current or not (old / "dojo-complete.json").is_file():
                continue
            if not old.resolve().is_relative_to(root):
                raise RuntimeError("Checkpoint escapes run")
            for f in old.rglob("*"):
                if (
                    f.is_file()
                    and not f.is_symlink()
                    and f.stat().st_size >= 1024 * 1024
                ):
                    removed.append({"path": str(f), "bytes": f.stat().st_size})
                    f.unlink()
        with (d / "retention.jsonl").open("a") as stream:
            stream.write(
                json.dumps(
                    {"time": time.time(), "kept": str(current), "removed": removed}
                )
                + "\n"
            )

    EmbodiedRunner._save_checkpoint = save_latest
    original_run = EmbodiedRunner.run

    def run(self):
        if phase == "final_eval":
            self.update_rollout_weights()
            metrics = self.evaluate()
            (d / "final-evaluation.json").write_text(
                json.dumps(
                    {"round": self.global_step, "episodes": 128, "metrics": metrics},
                    default=float,
                    indent=2,
                )
            )
            return self._finish_run()
        if self.global_step == 0 and phase == "formal":
            self.update_rollout_weights()
            metrics = self.evaluate()
            self.metric_logger.log(
                data={f"eval/{k}": v for k, v in metrics.items()}, step=0
            )
            with (d / "evaluations.jsonl").open("a") as f:
                f.write(
                    json.dumps(
                        {"round": 0, "time": time.time(), "metrics": metrics},
                        default=float,
                    )
                    + "\n"
                )
        return original_run(self)

    EmbodiedRunner.run = run
    original_evaluate = EmbodiedRunner._maybe_eval_and_checkpoint

    def evaluate_checkpoint(self, step):
        if phase in ("smoke", "smoke_resume"):
            # Smoke verifies real rollout/update/full recovery. Do not repeat
            # entire evaluation waves; the formal run keeps its own baseline.
            self._save_checkpoint()
            return {}
        metrics = original_evaluate(self, step)
        if self.global_step == 2 and self.cfg.runner.val_check_interval > 2:
            self.update_rollout_weights()
            metrics = {f"eval/{k}": v for k, v in self.evaluate().items()}
            self.metric_logger.log(data=metrics, step=step)
        if metrics:
            with (d / "evaluations.jsonl").open("a") as f:
                f.write(
                    json.dumps(
                        {
                            "round": self.global_step,
                            "time": time.time(),
                            "metrics": metrics,
                        },
                        default=float,
                    )
                    + "\n"
                )
            if phase == "formal":
                scores = [
                    float(v) for k, v in metrics.items() if k.endswith("success_once")
                ]
                if scores:
                    score = scores[0]
                    best = d / "best-evaluation.json"
                    old = (
                        json.loads(best.read_text())["success"]
                        if best.exists()
                        else -1.0
                    )
                    if score > old:
                        checkpoint = (
                            Path(self.cfg.runner.logger.log_path)
                            / self.cfg.runner.logger.experiment_name
                            / "checkpoints"
                            / f"global_step_{self.global_step}"
                        )
                        if not (checkpoint / "dojo-complete.json").is_file():
                            self._save_checkpoint()
                        # A peak survives later full-checkpoint rolling deletion.
                        protected = (
                            Path(plan["protected_output"])
                            / f"global_step_{self.global_step}"
                        )
                        protected.mkdir(parents=True, exist_ok=False)
                        shutil.copy2(
                            checkpoint / "actor/model_state_dict/full_weights.pt",
                            protected / "full_weights.pt",
                        )
                        shutil.copytree(
                            Path(plan["model"]) / "assets", protected / "assets"
                        )
                        receipt = {
                            "round": self.global_step,
                            "success": score,
                            "checkpoint": str(checkpoint),
                            "protected": str(protected),
                            "task": "put_bottles_into_dustbin",
                        }
                        (protected / "manifest.json").write_text(
                            json.dumps(receipt, indent=2)
                        )
                        best.write_text(json.dumps(receipt, indent=2))
        return metrics

    EmbodiedRunner._maybe_eval_and_checkpoint = evaluate_checkpoint
    spec = importlib.util.spec_from_file_location(
        "accepted_clean_ops", plan["legacy_ops"]
    )
    ops = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ops)
    ops.RUN = Path(plan["run"]) / f"driver-{phase}-{os.getpid()}"
    (ops.RUN / "runtime").mkdir(parents=True, exist_ok=True)
    ops.ROOT = Path(plan["training_source"])
    ops.NAMESPACE = plan["namespace"] + "_" + phase + "_" + str(os.getpid())
    sys.argv = [sys.argv[0], "formal_driver", *sys.argv[1:]]
    ops.formal_driver()
    if phase == "smoke":
        subprocess.run(
            [
                sys.executable,
                "-u",
                "-B",
                __file__,
                "--config-path",
                str(d / "config"),
                "--config-name",
                "smoke_resume",
            ],
            check=True,
        )
        (d / "smoke-resume-complete.json").write_text(
            json.dumps({"restored": 1, "completed": 2, "time": time.time()})
        )
    elif phase == "formal":
        subprocess.run(
            [
                sys.executable,
                "-u",
                "-B",
                __file__,
                "--config-path",
                str(d / "config"),
                "--config-name",
                "final_eval",
            ],
            check=True,
        )


if __name__ == "__main__":
    main()
